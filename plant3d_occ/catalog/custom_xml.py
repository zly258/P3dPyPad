# -*- coding: utf-8 -*-
"""AutoCAD Plant 3D `CustomScripts` Metadata & Registration File Generator.

Replicates the exact XML and map file structures generated by Plant 3D's
internal `varmain.custom._Dumper` (`PLANTREGISTERCUSTOMSCRIPTS`):
- `CustomScripts/<ScriptName>.xml` (`<ArrayOfScript>`)
- `CustomScripts/variants.map`
- `CustomScripts/ScriptGroup.xml`
- `CustomScripts/variants.xml`
"""

import io
import os
import re
from xml.sax.saxutils import escape


def write_custom_script_metadata(custom_scripts_dir: str, job: dict) -> dict:
    """Writes `<stem>.xml` and updates `variants.map`, `ScriptGroup.xml`, and `variants.xml`."""
    os.makedirs(custom_scripts_dir, exist_ok=True)

    # 部署全局 UTF-8 守护，确保 AutoCAD 内嵌 Python 2.7 解释器默认编码提升为 UTF-8
    site_py = os.path.join(custom_scripts_dir, "sitecustomize.py")
    if not os.path.isfile(site_py):
        try:
            with io.open(site_py, "w", encoding="utf-8") as s_fp:
                s_fp.write(u"# -*- coding: utf-8 -*-\nimport sys\ntry:\n    reload(sys)\n    sys.setdefaultencoding('utf-8')\nexcept Exception:\n    pass\n")
        except Exception:
            pass

    stem = job["stem"]
    group = job.get("group") or "Support"
    ports = int(job.get("ports") or 1)
    unit = job.get("length_unit") or "mm"
    # 显示名/描述由脚本自身的 @activate(TooltipShort/TooltipLong) 提供，Plant 3D
    # 运行时读脚本；.acat 里 LDesId/SDesId 只是本地化键（真机发布的 XML 也等于脚本名）。
    params = job.get("params_meta") or job.get("params") or []
    call_defaults = {}
    if job.get("sizes"):
        call_defaults = dict(job["sizes"][0].get("call") or {})
    if job.get("defaults"):
        for k, v in job["defaults"].items():
            call_defaults.setdefault(k, v)

    # 1. Write <stem>.xml
    xml_path = os.path.join(custom_scripts_dir, stem + ".xml")
    lines = [
        '<?xml version="1.0" encoding="utf-8"?>',
        '<ArrayOfScript xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance" xmlns:xsd="http://www.w3.org/2001/XMLSchema">',
        '\t<Script Name="%s" LDesId="%s" SDesId="%s" ConnPortNum="%d" LengthUnit="%s" '
        'ThumbnailImage="%s_200.png" ParamDimImage="%s_640.png" SCEditDimImage="%s_640.png" '
        'SizingImg="%s_640.png" SCESizingImg="%s_640.png">'
        % (
            escape(stem),
            escape(stem),
            escape(stem),
            ports,
            escape(unit),
            escape(stem),
            escape(stem),
            escape(stem),
            escape(stem),
            escape(stem),
        ),
        "\t\t<Params>",
    ]
    for idx, p in enumerate(params):
        if isinstance(p, dict):
            p_name = p["name"]
            p_type = p.get("type", "LENGTH")
            ask4dist = "true" if p.get("ask4dist") else "false"
            val = call_defaults.get(p_name, p.get("default", 0.0))
            pg = p.get("group") or "MainDimensions"
        else:
            p_name = p[0]
            p_type = p[1] if len(p) > 1 else "LENGTH"
            ask4dist = "false"
            val = call_defaults.get(p_name, 0.0)
            pg = "MainDimensions"
        lines.append(
            '\t\t\t<Param Name="%s" LDesId="%s.%s" SDesId="%s.%s" Type="%s" Ask4Dist="%s" Value="%s" pg="%s" />'
            % (
                escape(str(p_name)),
                escape(stem),
                escape(str(p_name)),
                escape(stem),
                escape(str(p_name)),
                escape(str(p_type)),
                ask4dist,
                escape(str(val)),
                escape(str(pg)),
            )
        )
    lines.append("\t\t</Params>")
    lines.append("\t</Script>")
    lines.append("</ArrayOfScript>")
    with io.open(xml_path, "w", encoding="utf-8-sig") as fp:
        fp.write("\n".join(lines) + "\n")

    # 2. Update variants.map
    map_path = os.path.join(custom_scripts_dir, "variants.map")
    entries = {}
    if os.path.isfile(map_path):
        with io.open(map_path, "r", encoding="utf-8", errors="ignore") as fp:
            for line in fp:
                line = line.strip()
                if "=" in line:
                    k, v = line.split("=", 1)
                    k = k.strip()
                    v = v.strip()
                    # 自动清理历史错误格式（移除多余的 \CustomScripts\ 与 .py 后缀）
                    clean_v = os.path.splitext(os.path.basename(v))[0] if v else k
                    entries[k] = clean_v
    # 官方标准映射：KEY=STEM（如 EQUIPMENT_CENTRIFUGAL_PUMP=EQUIPMENT_CENTRIFUGAL_PUMP，不带路径与 .py）
    entries[stem] = stem
    with io.open(map_path, "w", encoding="utf-8") as fp:
        for k in sorted(entries.keys()):
            fp.write("%s=%s\n" % (k, entries[k]))

    # 3. Update ScriptGroup.xml
    sg_path = os.path.join(custom_scripts_dir, "ScriptGroup.xml")
    sg_entries = {}
    if os.path.isfile(sg_path):
        with io.open(sg_path, "r", encoding="utf-8", errors="ignore") as fp:
            text = fp.read()
        for m in re.finditer(
            r"<ScriptGroup>\s*<ScriptName>([^<]+)</ScriptName>\s*<Group>([^<]*)</Group>\s*<FirstPortEndtypes>([^<]*)</FirstPortEndtypes>\s*</ScriptGroup>",
            text,
            re.S,
        ):
            sg_entries[m.group(1).strip()] = (m.group(2).strip(), m.group(3).strip())
    sg_entries[stem] = (group, job.get("first_port_endtypes", ""))
    sg_lines = [
        '<?xml version="1.0" encoding="utf-8"?>',
        "<ScriptInfo>",
    ]
    for sname in sorted(sg_entries.keys()):
        grp, fpe = sg_entries[sname]
        sg_lines.append("\t<ScriptGroup>")
        sg_lines.append("\t\t<ScriptName>%s</ScriptName>" % escape(sname))
        sg_lines.append("\t\t<Group>%s</Group>" % escape(grp))
        sg_lines.append("\t\t<FirstPortEndtypes>%s</FirstPortEndtypes>" % escape(fpe))
        sg_lines.append("\t</ScriptGroup>")
    sg_lines.append("</ScriptInfo>")
    with io.open(sg_path, "w", encoding="utf-8-sig") as fp:
        fp.write("\n".join(sg_lines) + "\n")

    return {
        "script_xml": xml_path,
        "variants_map": map_path,
        "script_group_xml": sg_path,
    }
